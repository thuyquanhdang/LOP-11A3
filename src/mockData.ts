export const generateSampleSubjectScores = (academicRating: 'Tốt' | 'Khá' | 'Đạt' | 'Chưa đạt'): SubjectScore[] => {
  const baseScores: Record<'Tốt' | 'Khá' | 'Đạt' | 'Chưa đạt', { min: number; max: number }> = {
    'Tốt': { min: 8.0, max: 9.8 },
    'Khá': { min: 6.5, max: 7.9 },
    'Đạt': { min: 5.0, max: 6.4 },
    'Chưa đạt': { min: 3.5, max: 4.9 },
  };
  const { min, max } = baseScores[academicRating] || baseScores['Khá'];

  return DEFAULT_SUBJECTS.map((subject) => {
    const randomScore = () => Number((Math.random() * (max - min) + min).toFixed(1));
    const tx1 = randomScore();
    const tx2 = randomScore();
    const tx3 = randomScore();
    const gk = randomScore();
    const ck = randomScore();
    const avg = Number(((tx1 + tx2 + tx3 + gk * 2 + ck * 3) / 8).toFixed(1));
    return {
      subjectName: subject,
      tx1,
      tx2,
      tx3,
      gk,
      ck,
      avg
    };
  });
};

export const generateSampleWeeklyEmulation = (conductRating: 'Tốt' | 'Khá' | 'Đạt' | 'Chưa đạt') => {
  const weeks: { [week: number]: 'Tốt' | 'Khá' | 'Đạt' | 'Chưa đạt' } = {};
  for (let w = 1; w <= 12; w++) {
    if (conductRating === 'Tốt') {
      weeks[w] = Math.random() > 0.15 ? 'Tốt' : 'Khá';
    } else if (conductRating === 'Khá') {
      weeks[w] = Math.random() > 0.3 ? 'Khá' : (Math.random() > 0.5 ? 'Tốt' : 'Đạt');
    } else {
      weeks[w] = Math.random() > 0.4 ? 'Đạt' : (Math.random() > 0.5 ? 'Khá' : 'Chưa đạt');
    }
  }
  return weeks;
};

